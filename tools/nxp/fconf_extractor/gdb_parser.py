"""
GDB Python Script to dump TF-A structures as C code
Usage:
1. Set breakpoint after fconf initialization
2. Source this script in GDB
3. Run: dump-fconf-structures output.c
"""

try:
    import gdb
except ImportError:
    # gdb module is only available when running inside GDB
    pass


def _is_unsigned_type(gdb_type):
    """Detect if integer-like type t is unsigned"""
    gdb_type = gdb_type.strip_typedefs()
    type_name = gdb_type.name or str(gdb_type)

    # Dynamic check: compile-time expression evaluated by GDB
    # Example: ((unsigned int)-1) < 0  -> False (unsigned)
    #          ((int)-1) < 0           -> True  (signed)
    expr = f"(({type_name})-1) < 0"
    return not bool(int(gdb.parse_and_eval(expr)))


def _format_integer_value(val):
    """Format GDB integer value as C literal."""
    val_type = val.type.strip_typedefs()
    if val_type.code not in (gdb.TYPE_CODE_INT, gdb.TYPE_CODE_ENUM, gdb.TYPE_CODE_CHAR):
        raise gdb.GdbError("Not an integer type")

    size = val_type.sizeof
    bits = size * 8
    raw = int(val)

    # Decide suffix
    suffix = ""
    if _is_unsigned_type(val_type):
        mask = (1 << bits) - 1
        unsigned_val = raw & mask
        hex_width = bits // 4
        core_num = f"0x{unsigned_val:0{hex_width}x}"
        suffix = "U"
    else:
        core_num = f"{raw}"

    if size == 8:
        suffix += "LL"
    elif size == 4:
        suffix += "L" if "long" in (val_type.name or "") else ""

    return f"{core_num}{suffix}"


def _format_pointer_value(val):
    """Format GDB pointer value as C literal."""
    if 'char' in str(val.type) and val.type.pointer():
        # String pointer
        try:
            str_val = val.string()
            return f'"{str_val}"'
        except gdb.MemoryError:
            return "NULL"
    addr = int(val)
    if addr == 0:
        return "NULL"
    return f"0x{addr:08x}"

def get_value_as_c(val):
    """Convert GDB value to C literal."""
    try:
        val_type_str = str(val.type)
        if val.type.strip_typedefs().code == gdb.TYPE_CODE_PTR:
            return _format_pointer_value(val)
        if 'int' in val_type_str or 'long' in val_type_str or 'char' in val_type_str:
            return _format_integer_value(val)
        if 'size_t' in val_type_str:
            if val.type.sizeof == 8:
                return f"0x{int(val):016x}ULL"
            return f"0x{int(val):08x}U"
        if val_type_str == 'bool' or '_Bool' in val_type_str:
            return "true" if int(val) != 0 else "false"
        return str(val)
    except (gdb.MemoryError, ValueError, TypeError) as error:
        gdb.write(f"Error reading value of type {val.type}: {error}")
        raise

class StructDumper:
    """Class to dump GDB structures as C code."""

    def __init__(self):
        self.output_file = None
        self.indent_level = 0

    def indent(self):
        """Return indentation string for current level."""
        return "    " * self.indent_level

    def write(self, text):
        """Write text to output file or stdout."""
        if self.output_file:
            self.output_file.write(text)
        else:
            print(text, end='')

    def writeln(self, text=""):
        """Write line to output file or stdout."""
        self.write(text + "\n")

    def dump_header(self, custom_includes=None):
        """Generate file header with optional custom includes."""
        self.writeln("/*")
        self.writeln(" * Copyright 2025 NXP")
        self.writeln(" *")
        self.writeln(" * SPDX-License-Identifier: BSD-3-Clause")
        self.writeln(" *")
        self.writeln(" * Generated by GDB structure dump")
        self.writeln(" *")
        self.writeln(" * DO NOT MODIFY")
        self.writeln(" *")
        self.writeln(" */")
        self.writeln()

        # Standard includes
        self.writeln("#include <stdint.h>")
        self.writeln("#include <stdbool.h>")

        # Custom includes
        if custom_includes:
            self.writeln()
            for include in custom_includes:
                # Handle both <> and "" style includes
                if include.startswith('<') and include.endswith('>'):
                    self.writeln(f"#include {include}")
                elif include.startswith('"') and include.endswith('"'):
                    self.writeln(f"#include {include}")
                else:
                    # Default to quoted includes for local files
                    self.writeln(f'#include "{include}"')

        self.writeln()

    def dump_footer(self):
        """Generate file footer."""
        self.writeln()

    def find_count_field_for_pointer(self, struct_type, pointer_field_name):
        """Find a count field that corresponds to a pointer field.

        Looks for field named: pointer_name + "_n_elem"
        """
        count_field_name = f"{pointer_field_name}_n_elem"

        for field in struct_type.fields():
            if field.name == count_field_name:
                return field.name

        return None

    def dump_dynamic_array_as_static(self, array_field_name, pointer_val, count_val, element_type):
        """Dump a dynamic array pointed to by pointer_val as a static array."""
        try:
            count = int(count_val)
            if count == 0:
                self.writeln(f"{self.indent()}.{array_field_name} = NULL,")
                return

            # Get the element type (remove pointer from pointer type)
            if element_type.code == gdb.TYPE_CODE_PTR:
                target_type = element_type.target()
            else:
                target_type = element_type

            # Get the actual type name for casting
            type_name = target_type.name
            if not type_name:
                type_name = str(target_type).strip()

            # Add struct keyword for struct types
            if target_type.code == gdb.TYPE_CODE_STRUCT:
                if not type_name.startswith('struct '):
                    type_name = f"struct {type_name}"

            self.writeln(f"{self.indent()}.{array_field_name} = ({type_name} []) {{")
            self.indent_level += 1

            # Get the pointer address as a number
            ptr_addr = int(pointer_val)

            for i in range(count):
                try:
                    # Use GDB expression evaluation to access array elements
                    element_addr = ptr_addr + (i * target_type.sizeof)
                    expr = f"*({type_name} *)0x{element_addr:x}"
                    element_val = gdb.parse_and_eval(expr)

                    if target_type.code == gdb.TYPE_CODE_STRUCT:
                        # Handle struct elements
                        self.writeln(f"{self.indent()}{{ // [{i}]")
                        self.indent_level += 1
                        self.dump_struct_fields(element_val)
                        self.indent_level -= 1
                        comma = "," if i < count - 1 else ""
                        self.writeln(f"{self.indent()}}}{comma}")
                    else:
                        # Handle primitive elements
                        c_val = get_value_as_c(element_val)
                        comma = "," if i < count - 1 else ""
                        self.writeln(f"{self.indent()}{c_val}{comma}  // [{i}]")

                except (gdb.MemoryError, ValueError, TypeError, gdb.error) as error:
                    gdb.write(f"Error reading array element {i}: {error}\n")
                    # Output a placeholder for failed reads
                    comma = "," if i < count - 1 else ""
                    self.writeln(f"{self.indent()}{{ /* Error reading element {i}: {error} */ }}{comma}")

            self.indent_level -= 1
            self.writeln(f"{self.indent()}}},")

        except (gdb.MemoryError, ValueError, TypeError, gdb.error) as error:
            gdb.write(f"Error dumping dynamic array {array_field_name}: {error}\n")
            self.writeln(f"{self.indent()}.{array_field_name} = NULL, /* Error: {error} */")

    def dump_struct_variable(self, var_name):
        """Dump a global structure variable."""
        try:
            # Get the variable
            var = gdb.parse_and_eval(var_name)

            type_name = str(var.type)

            # Start structure definition
            self.writeln(f"{type_name} {var_name} = {{")
            self.indent_level += 1

            # Dump structure fields
            self.dump_struct_fields(var)

            self.indent_level -= 1
            self.writeln("};")
            self.writeln()

        except gdb.error as gdb_error:
            gdb.write(f"Error dumping {var_name}: {gdb_error}\n")
            raise

    def find_dynamic_array_pairs(self, struct_type):
        """Find all pointer/count field pairs in the struct.

        Returns a dict mapping pointer field names to their count field names.
        """
        dynamic_pairs = {}

        # Get all field names first
        all_fields = {field.name: field for field in struct_type.fields() if field.name is not None}

        # Look for pointer fields and their corresponding count fields
        for field_name, field in all_fields.items():
            if field.type.code != gdb.TYPE_CODE_PTR:
                continue

            count_field_name = self.find_count_field_for_pointer(struct_type, field_name)
            if count_field_name:
                dynamic_pairs[field_name] = count_field_name
                gdb.write(f"Identified dynamic array pair: {field_name} + {count_field_name}\n")

        return dynamic_pairs

    def process_dynamic_array_pair(self, struct_val, pointer_field_name, count_field_name, processed_fields):
        """Process a pointer/count field pair as a dynamic array."""
        try:
            pointer_field_val = struct_val[pointer_field_name]
            count_field_val = struct_val[count_field_name]
            pointer_field_type = struct_val[pointer_field_name].type.strip_typedefs()

            count = int(count_field_val)
            gdb.write(f"Processing dynamic array pair: {pointer_field_name} (ptr) + {count_field_name} (count={count})\n")

            if count > 0 and int(pointer_field_val) != 0:
                gdb.write(f"Expanding dynamic array: {pointer_field_name} with {count} elements\n")
                self.dump_dynamic_array_as_static(pointer_field_name, pointer_field_val, count_field_val, pointer_field_type)
            else:
                # Count is 0 or pointer is null, dump NULL pointer
                self.writeln(f"{self.indent()}.{pointer_field_name} = NULL,")

            # Always dump the count field
            c_count_val = get_value_as_c(count_field_val)
            count_field_type_str = str(count_field_val.type)
            self.writeln(f"{self.indent()}.{count_field_name} = "
                       f"({count_field_type_str}){c_count_val},")

            # Mark both fields as processed
            processed_fields.add(pointer_field_name)
            processed_fields.add(count_field_name)

            return True

        except Exception as error:
            gdb.write(f"Error processing dynamic array pair {pointer_field_name}/{count_field_name}: {error}\n")
            return False

    def process_regular_field(self, struct_val, field):
        """Process a regular (non-dynamic-array) field."""
        field_val = struct_val[field.name]
        field_type = field.type

        if field_type.code == gdb.TYPE_CODE_STRUCT:
            # Nested structure
            self.writeln(f"{self.indent()}.{field.name} = {{")
            self.indent_level += 1
            self.dump_struct_fields(field_val)
            self.indent_level -= 1
            self.writeln(f"{self.indent()}}},")

        elif field_type.code == gdb.TYPE_CODE_ARRAY:
            # Static array field
            self.dump_array_field(field.name, field_val)

        else:
            # Simple field (including regular pointers)
            c_val = get_value_as_c(field_val)
            field_type_str = str(field_type)
            self.writeln(f"{self.indent()}.{field.name} = "
                         f"({field_type_str}){c_val},")

    def dump_struct_fields(self, struct_val):
        """Recursively dump structure fields."""
        try:
            struct_type = struct_val.type
            processed_fields = set()  # Track fields we've already processed

            if struct_type.code != gdb.TYPE_CODE_STRUCT:
                gdb.write(f"Error reading struct: {struct_val}\n")
                raise

            # First pass: identify all dynamic array pairs
            dynamic_pairs = self.find_dynamic_array_pairs(struct_type)

            # Second pass: process fields in order, handling dynamic arrays appropriately
            for field in struct_type.fields():
                if field.name is None or field.name in processed_fields:
                    continue

                try:
                    # Check if this field is part of a dynamic array pair
                    if field.name in dynamic_pairs:
                        # This is a pointer field with a count field - process as dynamic array
                        count_field_name = dynamic_pairs[field.name]
                        if self.process_dynamic_array_pair(struct_val, field.name, count_field_name, processed_fields):
                            continue  # Successfully processed, move to next field

                    elif field.name in dynamic_pairs.values():
                        # This is a count field for a dynamic array - skip it here
                        # It will be processed when we encounter its corresponding pointer field
                        # But check if the pointer field was already processed
                        pointer_field_name = None
                        for ptr_name, count_name in dynamic_pairs.items():
                            if count_name == field.name:
                                pointer_field_name = ptr_name
                                break

                        if pointer_field_name and pointer_field_name not in processed_fields:
                            # Pointer field hasn't been processed yet, skip this count field for now
                            continue
                        elif pointer_field_name and pointer_field_name in processed_fields:
                            # Pointer field was already processed, skip this count field
                            processed_fields.add(field.name)
                            continue

                    # Process as regular field (only if not already processed)
                    if field.name not in processed_fields:
                        self.process_regular_field(struct_val, field)
                        processed_fields.add(field.name)

                except (gdb.MemoryError, ValueError, TypeError) as field_error:
                    gdb.write(f"Error reading field {field.name}: {field_error}\n")
                    raise

        except (gdb.MemoryError, ValueError, TypeError) as struct_error:
            gdb.write(f"Error reading struct: {struct_error}\n")
            raise

    def dump_array_field(self, field_name, array_val):
        """Dump array field."""
        try:
            array_type = array_val.type
            if array_type.code == gdb.TYPE_CODE_ARRAY:
                # Get array dimensions
                low_bound = array_type.range()[0]
                high_bound = array_type.range()[1]
                count = high_bound - low_bound + 1

                self.writeln(f"{self.indent()}.{field_name} = {{")
                self.indent_level += 1

                for i in range(count):
                    try:
                        elem_val = array_val[i]
                        elem_code = elem_val.type.code

                        if elem_code == gdb.TYPE_CODE_STRUCT:
                            # Nested structure in array
                            self.writeln(f"{self.indent()}{{")
                            self.indent_level += 1
                            self.dump_struct_fields(elem_val)
                            self.indent_level -= 1
                            comma = "," if i < count - 1 else ""
                            self.writeln(f"{self.indent()}}}{comma}")
                        else:
                            c_val = get_value_as_c(elem_val)
                            comma = "," if i < count - 1 else ""
                            self.writeln(f"{self.indent()}{c_val}{comma}")

                    except (gdb.MemoryError, ValueError, TypeError):
                        gdb.write(f"Error reading array element {i}\n")
                        raise

                self.indent_level -= 1
                self.writeln(f"{self.indent()}}},")
        except (gdb.MemoryError, ValueError, TypeError) as array_error:
            gdb.write(f"Error dumping array {field_name}: {array_error}\n")
            raise


class DumpFconfStructuresCommand(gdb.Command):
    """Dump fconf structures to a header file.

    Usage:
        dump-fconf-structures <output-file> <struct1> [struct2 ...] [--include <file1> <file2> ...]
    Example:
        dump-fconf-structures \
            output.c \
            gic_config foo_cfg bar_cfg \
            --include "lib/fconf/fconf.h" "plat/common/platform.h"
    """

    def __init__(self):
        super().__init__("dump-fconf-structures", gdb.COMMAND_USER)

    def print_usage(self):
        """Print usage information."""
        gdb.write("Usage: dump-fconf-structures <output-file> <struct1> [struct2 ...] [--include <file1> <file2> ...]\n")
        gdb.write("Example: dump-fconf-structures output.h gic_config dyn_config --include \"lib/fconf/fconf.h\" \"plat/common/platform.h\"\n")

    def invoke(self, args, _from_tty):
        """Invoke the dump command."""
        args = args.strip()
        if not args:
            self.print_usage()
            return

        tokens = args.split()
        if len(tokens) < 2:
            self.print_usage()
            return

        # Parse arguments
        output_file = tokens[0]
        structures = []
        includes = []

        # Find the --include separator if it exists
        include_index = -1
        try:
            include_index = tokens.index("--include")
        except ValueError:
            # --include not found, all remaining tokens are structures
            include_index = len(tokens)

        # Extract structures (from index 1 to --include or end)
        if include_index > 1:
            structures = tokens[1:include_index]

        # Extract includes (everything after --include)
        if include_index != -1 and include_index < len(tokens) - 1:
            includes = tokens[include_index + 1:]

        if not structures:
            gdb.write("Error: No structures specified\n")
            self.print_usage()
            return

        # Check global_ret variable after parameters are interpreted
        try:
            global_ret_var = gdb.parse_and_eval("global_ret")
            if int(global_ret_var) != 0:
                raise gdb.error(f"global_ret is not zero (value: {int(global_ret_var)}). Cannot proceed with structure dump.")
        except gdb.error as gdb_error:
            # Re-raise GDB errors (including our custom one above)
            raise
        except Exception as error:
            # Handle other errors like variable not found
            raise gdb.error(f"Error accessing global_ret variable: {error}")

        dumper = StructDumper()

        try:
            with open(output_file, 'w', encoding='utf-8') as output_handle:
                dumper.output_file = output_handle
                dumper.dump_header(includes)

                for var_name in structures:
                    dumper.dump_struct_variable(var_name)

                dumper.dump_footer()

            gdb.write(f"Structures dumped to {output_file}: {', '.join(structures)}\n")
            if includes:
                gdb.write(f"Includes added: {', '.join(includes)}\n")

        except (IOError, OSError) as io_error:
            gdb.write(f"[dump-fconf-structures] Error: {io_error}\n")
            raise


DumpFconfStructuresCommand()

# Print usage instructions
print("TF-A Structure Dumper loaded!")
print("Available commands:")
print("  dump-fconf-structures <output.h>  - Dump structures to C header file")
print("\nUsage:")
print("1. Set a breakpoint after FCONF parsing is complete")
print("2. Run until the excution reaches the breakpoint() function")
print("3. Use dump-fconf-structures output.c")
